class ResBlk(nn.Module):
    def __init__(
            self,
            in_chs: int,
            out_chs: int,
            norm_eps: float = 1e-5,
    ) -> None:
        super().__init__()
        self.proj = in_chs != out_chs
        self.conv1 = nn.Conv2d(
            in_channels=in_chs,
            out_channels=in_chs,
            kernel_size=3,
            stride=1,
            padding=1,
            bias=False,
        )
        # self.norm1 = nn.GroupNorm(num_groups=_gn_groups(in_chs), num_channels=in_chs)
        self.norm1 = nn.BatchNorm2d(in_chs)
        self.act = nn.SiLU()
        self.conv2 = nn.Conv2d(
            in_channels=in_chs,
            out_channels=out_chs,
            kernel_size=3,
            stride=1,
            padding=1,
            bias=False,
        )
        # self.norm2 = nn.GroupNorm(num_groups=_gn_groups(out_chs), num_channels=out_chs)
        self.norm2 = nn.BatchNorm2d(out_chs)
        if self.proj:
            self.conv3 = nn.Conv2d(
                in_channels=in_chs,
                out_channels=out_chs,
                kernel_size=1,
                stride=1,
                padding=0,
                bias=False,
            )
            # self.norm3 = nn.GroupNorm(num_groups=_gn_groups(out_chs), num_channels=out_chs)
            self.norm3 = nn.BatchNorm2d(out_chs)

    def forward(self, x: Tensor) -> Tensor:
        _x = x
        x = self.conv1(x)
        x = self.norm1(x)
        x = self.act(x)
        x = self.conv2(x)
        x = self.norm2(x)
        if self.proj:
            _x = self.conv3(_x)
            _x = self.norm3(_x)
        x = _x + x
        x = self.act(x)

        return x


class DWConv(nn.Module):
    def __init__(self, dim=768):
        super(DWConv, self).__init__()
        self.dwconv = nn.Conv2d(dim, dim, 3, 1, 1, bias=True, groups=dim)

    def forward(self, x, H, W):
        B, N, C = x.shape
        x = x.transpose(1, 2).view(B, C, H, W)
        x = self.dwconv(x)
        x = x.flatten(2).transpose(1, 2)

        return x

